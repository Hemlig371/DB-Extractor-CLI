CREATE TABLE parity_big AS
SELECT level AS id, LOWER(STANDARD_HASH(TO_CHAR(level), 'MD5')) AS h, MOD(level, 1000) AS k,
       level * 1.5 AS f, CASE WHEN MOD(level, 7) = 0 THEN NULL ELSE 'row ' || level END AS s
FROM dual CONNECT BY level <= 20000;

